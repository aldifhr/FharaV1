/**
 * Pure helpers that turn skills/builtin/<name>/SKILL.md into the generated
 * builtinSkills.data.ts (used by scripts/build-builtin-skills.ts and the
 * parity test). No Node or Convex APIs.
 */
import { parseFrontMatter } from "./githubSkills";

export type BuiltinSkillSource = {
  /** Folder name under skills/builtin, the stable built-in key. */
  key: string;
  name: string;
  description: string;
  /** SPDX id from the front matter. */
  license: string;
  /** SKILL.md body after the front matter (attribution comment included). */
  instructions: string;
};

export function readBuiltinSkillSources(files: Array<{ folder: string; text: string }>): BuiltinSkillSource[] {
  return files
    .map(({ folder, text }) => {
      const { data, body } = parseFrontMatter(text);
      if (!data.name || !data.description || !data.license) {
        throw new Error(`skills/builtin/${folder}/SKILL.md needs name, description and license front matter`);
      }
      return { key: folder, name: data.name, description: data.description, license: data.license, instructions: body };
    })
    .sort((a, b) => a.key.localeCompare(b.key));
}

export function renderBuiltinSkillData(skills: BuiltinSkillSource[]): string {
  return [
    "// GENERATED by `npm run skills:builtin` from skills/builtin/*/SKILL.md. Do not edit by hand.",
    "// Licences and attribution: skills/builtin/README.md and THIRD_PARTY_NOTICES.md.",
    'import type { BuiltinSkillSource } from "./builtinSkillSource";',
    "",
    `export const BUILTIN_SKILL_SOURCES: readonly BuiltinSkillSource[] = ${JSON.stringify(skills, null, 2)};`,
    "",
  ].join("\n");
}
