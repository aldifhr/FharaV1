/**
 * Role prompt templates: the editable sources are the markdown files in
 * ./roles/ (one per role). Convex and the worker cannot read files at run
 * time, so `npm run prompts:roles` (scripts/build-role-prompts.ts) bundles
 * them into rolePrompts.data.ts with `renderRolePromptData`. A worker test
 * (tests/rolePromptsSource.test.ts) fails when the two drift apart.
 *
 * Pure: no Convex, Node or DOM APIs.
 */
import { ROLE_KEYS, type RoleKey } from "../roles";

/** The markdown file under ./roles/ that holds each role's template. */
export const ROLE_PROMPT_FILES: Record<RoleKey, string> = {
  cto: "CTO.md",
  designer: "DESIGNER.md",
  frontend: "FRONTEND.md",
  backend: "BACKEND.md",
  qa: "QA.md",
  support: "SUPPORT.md",
  devops: "DEVOPS.md",
  reviewer: "REVIEWER.md",
  researcher: "RESEARCHER.md",
};

/** A source file's text as stored: LF line ends, no surrounding blank space. */
export function normalizeRolePrompt(text: string): string {
  return text.replace(/\r\n?/g, "\n").trim();
}

/** The generated module's full text, from each role's markdown source. */
export function renderRolePromptData(sources: Record<RoleKey, string>): string {
  const entries = ROLE_KEYS.map((key) => {
    const text = normalizeRolePrompt(sources[key] ?? "");
    if (!text) throw new Error(`Role prompt ${ROLE_PROMPT_FILES[key]} is empty`);
    return `  ${key}: ${JSON.stringify(text)},`;
  });
  return [
    "// GENERATED by `npm run prompts:roles` from apps/api/convex/lib/prompts/roles/*.md. Do not edit by hand.",
    'import type { RoleKey } from "../roles";',
    "",
    "export const ROLE_PROMPT_TEMPLATES: Record<RoleKey, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}
